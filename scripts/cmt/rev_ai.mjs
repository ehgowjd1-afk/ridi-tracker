const E = (o) => Object.keys(o);
const list = (o) => Object.entries(o).map(([k, v]) => `${k}=${v}`).join(", ");

export const REV_THEME_SYSTEM = `당신은 한국 웹소설·웹툰 플랫폼 리디(RIDI)의 구매자 별점 리뷰에서 '독자들이 반복해서 하는 말'을 찾는 분석가입니다. 숨은 뜻을 해석하지 말고, 독자들이 실제로 되풀이하는 말을 있는 그대로 묶되, 결과에는 리뷰 원문을 옮겨 적지 않습니다(결과가 공개되므로 근거는 refs 번호로만). 결과는 기획자가 "이 작품 리뷰에서 이런 말이 반복된다, 이런 불호가 있다"를 보는 데 쓰입니다.

## 할 일
리뷰 표본(별점·공감 수 포함)을 읽고, 여러 리뷰에서 되풀이되는 말을 15~22개 묶음으로 정리합니다. 목표는 '무언가 구체적인 말을 하는 리뷰'의 대부분이 어느 한 묶음에 들어가게 하는 것입니다.
- 리뷰는 작품 전체(또는 읽은 데까지)를 평가하는 글입니다. 이런 반응을 빠뜨리지 않았는지 확인합니다: 스토리·전개, 인물별 매력(외모·성격), 커플 케미·관계, 설정·세계관·소재, 작화·연출(웹툰) 또는 문장·필력(웹소설), 수위·씬, 분위기·감정(설렘·눈물·웃음), 원작 비교·각색, 결말·완결·외전, 작가 신뢰, 가격·분량, 재독·정주행, 추천 대상('~ 좋아하는 분께 추천'), 호불호 안내('키워드 주의', '호불호 갈릴 듯'), 아쉬운 점.
- 각 묶음:
  · bucket: like(좋다는 말) / talk(많이 하는 말) / dislike(불호)
  · label: 여러 리뷰가 공통으로 하는 말을 25자 안팎으로, 독자 말투에 가깝게 자기 말로 요약. 특정 리뷰 문장을 그대로 옮기지 않는다(예: '공의 집착이 설레고 좋다', '완결이라 아쉽고 외전을 바란다', '중반부터 전개가 늘어진다')
  · def: 다른 AI가 리뷰 하나하나를 이 묶음에 넣을지 판단할 기준. 60자 안팎. 헷갈리는 이웃 묶음과 어떻게 다른지도 짧게. 리뷰 문장을 옮기지 않는다.
  · refs: 근거 리뷰 번호 2~5개

## bucket 기준 (가장 중요)
- like: 작품·인물·관계·장면·작화·문장을 좋다고 하는 말. 반어·밈으로 한 칭찬('외모가 반칙', '돈이 안 아깝다 못해 죄송하다')도 like.
- talk: 좋다·싫다로 가르기 애매하거나 화제인 말:
  · 캐릭터에게 화내기·놀리기·서운함(별점이 높고 작품을 즐기는 리뷰에서) — 과몰입
  · 완결·외전 바람, 연재 기다림·휴재나 업데이트가 느리다는 불평(화를 내거나 별을 깎아도 talk), 분량이 짧아 아쉬움, 원작 비교·원작 질문, 추천 대상, 호불호·키워드 안내, 재독·정주행 이야기, 가격·이벤트 이야기
  · 칭찬과 함께 하는 아쉬운 점('재밌는데 후반이 좀 급해요', '좋은데 오타가 많아요') — 애정 섞인 지적은 불호가 아니라 talk. 단 결론이 여전히 좋다·계속 본다일 때만. '초반은 좋았는데 ~해서 하차', '1부는 명작인데 2부는 서사가 무너졌다'처럼 서사·캐릭터 때문에 결론이 하차·실망이면 dislike.
  · 같은 아쉬운 점(예: 후반 전개가 급하다)이 애정 섞인 지적으로도, 진지한 비판으로도 나오면 talk 묶음('재밌지만 후반이 급해 아쉽다')과 dislike 묶음('후반 전개가 급해 실망')을 따로 만들고, dislike 묶음의 def에는 '칭찬 없이 실망·하차일 때만'을 적는다. 이 짝은 겹치는 묶음으로 보지 않는다.
- dislike: **서사나 캐릭터**를 분명하게 싫다고 하는 말만 —
  · 서사: 스토리·전개(늘어짐·고구마·반복)·개연성·설정·세계관·결말·관계 전개, 과한 수위·고어 같은 내용 묘사에 대한 진지한 비판
  · 캐릭터: 인물의 성격·행동·매력이 싫다, 캐붕, 인물이 이상해서 못 보겠다
  · 서사·캐릭터 때문에 하차·실망했다는 말. 대개 별점이 낮다.
  · 서사·캐릭터가 아닌 불만은 아무리 진지해도 dislike가 아니라 talk: 휴재·지각·연재 주기·업데이트, 분량, 가격·'돈 아깝다'(서사·캐릭터 이유 없이), 작화·그림체, 문장·오탈자·교정, 작품 소개 문구, 뷰어·플랫폼·이벤트.
  · 별점은 참고만 한다: 별 1개라도 '완결이라 슬퍼서', '외전 내놔', '오류로 잘못 눌렀다'처럼 작품이 싫다는 뜻이 아니면 dislike가 아니다. 별 5개 리뷰의 가벼운 지적은 talk.
  · 뷰어 오류·플랫폼·이벤트·휴재·연재 주기 불만은 화를 내거나 하차를 말해도 dislike가 아니다(talk).
  · 분명한 근거가 여러 개 없으면 dislike 묶음을 만들지 않는다. 0개여도 된다.

## 주의
- 먼저 작품 전체에 걸친 반응을 찾고, 특정 회차·권에 몰린 반응만 따로 묶는다.
- 묶음끼리 겹치지 않게. '재밌다'처럼 너무 넓은 묶음은 만들지 않는다 — 무엇이 좋은지 구체적으로. 한 묶음 = 한 가지 반응.
- '재밌어요', '최고'뿐인 리뷰는 묶지 않아도 된다(분류에서 '해당 없음'으로 남음).
- 지어내지 않는다. 표본에 실제로 여러 번 나온 말만.`;

export function buildRevThemeParams(cfg, text) {
  const req = {
    model: cfg.model, max_tokens: 32000, system: REV_THEME_SYSTEM,
    messages: [{ role: "user", content: text + "\n\n위 리뷰 표본에서 반복되는 반응 묶음을 JSON으로 정리하세요." }],
    output_config: { format: { type: "json_schema", schema: THEME_SCHEMA } }
  };
  if (cfg.effort) req.output_config.effort = cfg.effort;
  return req;
}

export const REV_CLASSIFY_SCHEMA = {
  type: "object", additionalProperties: false, required: ["reviews"],
  properties: {
    reviews: {
      type: "array",
      items: {
        type: "object", additionalProperties: false, required: ["n", "th", "tn", "cf"],
        properties: {
          n: { type: "integer" },
          th: { type: "array", items: { type: "string" } },
          tn: { type: "string", enum: E(TONES) },
          cf: { type: "string", enum: E(CONFS) }
        }
      }
    }
  }
};

export const REV_CLASSIFY_SYSTEM = `당신은 한국 웹소설·웹툰 플랫폼 리디(RIDI)의 구매자 별점 리뷰를 하나하나 읽고 표시를 붙이는 분석가입니다. 해석보다 '이 리뷰가 무슨 말을 하는지'를 정확히 잡는 것이 목표입니다.

리뷰마다 아래 칸을 채웁니다.
- th 반복 반응: 입력의 [반복 반응 목록]에서 이 리뷰가 해당하는 묶음 번호(T1, T2 …) 0~3개. 리뷰마다 목록 전체를 훑어, 리뷰가 하는 말이 어떤 묶음의 기준(def) 범위 안에 들면 넣는다 — 묶음 이름과 표현이 똑같지 않아도 넣는다. 리뷰는 여러 가지를 말할 수 있으니 해당하는 묶음을 모두(최대 3개). '재밌어요', '최고'처럼 구체적인 말이 없거나 맞는 묶음이 정말 없을 때만 [].
  (불호) 묶음은 tn=critic일 때만 고른다 — 애정 섞인 지적·캐릭터 과몰입·완결 아쉬움은 (많이 하는 말) 묶음에서 고른다. (불호) 묶음 내용에 맞지만 tn이 critic이 아니면 같은 내용의 (많이 하는 말) 묶음을 고르고, 없으면 그 묶음은 고르지 않는다.
- tn 리뷰 전체의 속뜻(겉말이 아니라 속뜻 기준 하나): ${list(TONES)}
- cf 확신도: ${list(CONFS)}

## 속뜻(tn)
- 판별 질문: 작가가 작품 내용·그리는 방식을 고쳐야 한다고 '진지하게' 탓하거나 작품이 싫다고 하는가(지금도 좋아하는 마음 없이 — 하차·비추천·돈 아깝다로 끝나는 리뷰 포함) → critic. 칭찬과 함께 아쉬운 점을 말하는가 → nudge. 작중 인물에게 화내거나 놀리며 즐기는가 → char. 완결·외전·연재를 아쉬워하는가 → miss.
- praise 칭찬: 작품·인물·관계·작화·문장을 좋다고 함. 대부분의 리뷰.
- char 캐릭터 과몰입: 인물에게 화·욕·놀림·서운함을 표현하지만 작품을 즐김('남주 쓰레기ㅠㅠ 패고 싶다 근데 최애').
- tease 애정 투정·반어·밈: 불평처럼 보이지만 속은 좋아함('작가님 저한테 왜 이러세요ㅠ 밤새 읽음', 'X 얘기 그만해'를 X 범벅으로).
- miss 연재·완결 아쉬움: 완결이라 슬픔, 외전 바람, 연재 기다림, 분량 아쉬움 = 더 보고 싶다. 휴재·연재 주기·업데이트 지연·다음 권 출간 지연 이야기는 비꼬거나 화를 내도, 별점을 깎아도 miss다(예: '공지도 없이 또 휴재, 별 하나 뺌').
- nudge 애정 섞인 지적: 작품을 여전히 좋아하거나 계속 볼 마음이 있으면서 하는 지적. 칭찬·부탁과 함께 하는 지적('재밌는데 후반이 급해요', '좋은데 오타가 많아요'), 투정 말투의 진도 불평.
- critic 진짜 작품 불만: 지금도 좋아하는 마음 없이 작품을 부정적으로 평가(앞에 지난 칭찬이 있어도 결론이 하차·실망·돈 아까움이면 critic) — 전개·개연성·캐붕·결말·작화·문장·과한 수위에 대한 진지한 비판, 인물이 싫어서 못 보겠다, 이유가 붙은 하차, 돈이 아깝다.
- theory 추리·예측, fan 다른 독자·플랫폼·이벤트 이야기, other 단순·중립(정보·질문·방향 모를 말).
- 별점은 참고만: 별 1개라도 '완결이라 슬퍼서'면 miss, '실수로 눌렀다'면 other. 별 5개라도 진지한 비판이 중심이면 critic일 수 있다. 칭찬과 비판이 섞이면 리뷰의 결론을 따른다: 여전히 좋다·계속 본다·조금 아쉽다로 끝나면 nudge, 앞에 칭찬('초반은 재밌었는데', '1부는 명작인데')이 있어도 하차·비추천·돈(시간)이 아깝다·실망했다로 끝나면 critic. '~했는데'처럼 지난 일로 한 칭찬은 지금의 애정이 아니다.
- 뷰어 오류·결제·이벤트 불만은 작품 평가가 아니므로 critic이 아니라 fan. 휴재·연재 지연 불만도 작품 평가가 아니므로 critic이 아니라 miss.

## 출력
입력의 리뷰 번호(#n)마다 하나씩, 빠짐없이 JSON으로 답한다. 지어내지 않는다.`;

export function buildRevClassifyParams(cfg, work, reviews, textMax, themes) {
  const body = `[작품] ${work.title} / ${work.webtoon ? "웹툰" : "웹소설"}${work.bl ? " / BL" : ""}\n[작품 소개] ${work.desc || "-"}\n\n` +
    `[반복 반응 목록]\n` + themes.map((t) => `${t.id} (${BUCKETS[t.bucket]}) ${t.label} — 기준: ${t.def}`).join("\n") +
    "\n\n[리뷰]\n" + reviews.map((r) => `#${r.n} [★${r.rating} · 공감 ${r.likes}] ${cut(r.content.replace(/\s+/g, " "), textMax)}`).join("\n") +
    "\n\n위 리뷰에 규칙대로 표시를 붙여 JSON으로 답하세요.";
  const req = {
    model: cfg.model, max_tokens: 32000,
    system: [{ type: "text", text: REV_CLASSIFY_SYSTEM, cache_control: { type: "ephemeral" } }],
    messages: [{ role: "user", content: body }],
    output_config: { format: { type: "json_schema", schema: REV_CLASSIFY_SCHEMA } }
  };
  if (cfg.effort) req.output_config.effort = cfg.effort;
  return req;
}
